import {
  lightSpecSchema,
  materialSchema,
  modelAnimSchema,
  nodeIdSchema,
  opListSchema,
  sceneDocSchema,
  stageStateSchema,
  vec3,
} from '@vibebyte/vibe3d-protocol';
import { z } from 'zod';
import { revisionOut, roomId, transformInput } from './common';

const nodePatch = z.object({
  name: z.string().min(1).max(200).optional(),
  visible: z.boolean().optional(),
  transform: transformInput.optional(),
  light: lightSpecSchema.optional(),
  anim: modelAnimSchema.nullable().optional(),
});

export const sceneOps = {
  'scene.get': {
    title: '取整份场景文档',
    input: z.object({ roomId }),
    output: z.object({ revision: z.number().int().min(0), doc: sceneDocSchema }),
    scope: 'room' as const,
    mutating: false,
    wire: 'scene.get' as const,
    mcp: { tool: 'vibe3d_get_scene' as const, annotations: { readOnlyHint: true } },
    cli: { command: 'scene get', args: '<roomId>' },
    errors: ['E_ROOM_NOT_FOUND'] as const,
  },
  'scene.summary': {
    title: '场景摘要：节点数、资产、相机、舞台',
    input: z.object({ roomId }),
    output: z.object({
      revision: z.number().int().min(0),
      nodeCount: z.number().int().min(0),
      roots: z.array(nodeIdSchema),
      materials: z.array(z.string()),
      assets: z.array(z.string()),
      camera: z.object({ p: vec3, target: vec3, fov: z.number() }),
      stage: stageStateSchema,
    }),
    scope: 'room' as const,
    mutating: false,
    wire: 'scene.summary' as const,
    mcp: { tool: 'vibe3d_scene_summary' as const, annotations: { readOnlyHint: true } },
    cli: { command: 'scene summary', args: '<roomId>' },
    errors: ['E_ROOM_NOT_FOUND'] as const,
  },
  'ops.apply': {
    title: '原子应用一批 op，返回逆操作',
    input: z.object({
      roomId,
      ops: opListSchema,
      dryRun: z.boolean().optional(),
      baseRevision: z.number().int().min(0).optional(),
      opId: z.string().min(1).max(120).optional(),
    }),
    output: z.object({
      revision: z.number().int().min(0),
      applied: z.number().int().min(0),
      warnings: z.array(z.string()),
      inverse: opListSchema,
    }),
    scope: 'room' as const,
    mutating: true,
    wire: 'scene.apply' as const,
    mcp: { tool: 'vibe3d_apply_ops' as const, annotations: { readOnlyHint: false } },
    cli: { command: 'scene apply', args: '<roomId> --ops <json|@file>' },
    errors: ['E_INVALID_PARAMS', 'E_CONFLICT', 'E_PAYLOAD_TOO_LARGE', 'E_ROOM_NOT_FOUND'] as const,
  },
  'node.create': {
    title: '建节点：基础体 / 组 / 灯光',
    input: z.object({
      roomId,
      kind: z.enum(['mesh', 'group', 'light']),
      name: z.string().min(1).max(200).optional(),
      parent: nodeIdSchema.nullable().optional(),
      shape: z.enum(['box', 'sphere', 'cylinder', 'plane']).optional(),
      size: vec3.optional(),
      radius: z.number().positive().optional(),
      height: z.number().positive().optional(),
      color: z
        .string()
        .regex(/^#[0-9a-fA-F]{6}$/)
        .optional(),
      material: materialSchema.optional(),
      light: lightSpecSchema.optional(),
      transform: transformInput.optional(),
    }),
    output: z.object({ nodeId: nodeIdSchema, revision: z.number().int().min(0) }),
    scope: 'room' as const,
    mutating: true,
    wire: 'scene.apply' as const,
    mcp: { tool: 'vibe3d_create_node' as const },
    cli: { command: 'node create', args: '<roomId> --kind mesh --shape box' },
    errors: ['E_INVALID_PARAMS', 'E_PAYLOAD_TOO_LARGE', 'E_ROOM_NOT_FOUND'] as const,
  },
  'node.update': {
    title: '改节点：名称、可见、变换、灯光、动画参数',
    input: z.object({ roomId, nodeId: nodeIdSchema, patch: nodePatch }),
    output: revisionOut,
    scope: 'room' as const,
    mutating: true,
    wire: 'scene.apply' as const,
    mcp: { tool: 'vibe3d_update_node' as const },
    cli: { command: 'node update', args: '<roomId> <nodeId> --patch <json>' },
    errors: ['E_INVALID_PARAMS', 'E_ROOM_NOT_FOUND'] as const,
  },
  'node.delete': {
    title: '删节点，默认级联子树',
    input: z.object({ roomId, nodeId: nodeIdSchema, cascade: z.boolean().optional() }),
    output: revisionOut.extend({ deleted: z.number().int().min(1) }),
    scope: 'room' as const,
    mutating: true,
    wire: 'scene.apply' as const,
    mcp: { tool: 'vibe3d_delete_node' as const },
    cli: { command: 'node rm', args: '<roomId> <nodeId> [--no-cascade]' },
    errors: ['E_INVALID_PARAMS', 'E_ROOM_NOT_FOUND'] as const,
  },
  'stage.set': {
    title: '换舞台预设：光影、背景、地面',
    input: z.object({ roomId, stage: stageStateSchema.partial() }),
    output: revisionOut.extend({ stage: stageStateSchema }),
    scope: 'room' as const,
    mutating: true,
    wire: 'scene.apply' as const,
    mcp: { tool: 'vibe3d_set_stage' as const },
    cli: { command: 'stage set', args: '<roomId> --preset cine' },
    errors: ['E_INVALID_PARAMS', 'E_ROOM_NOT_FOUND'] as const,
  },
  'animation.play': {
    title: '播放模型动画，默认取首条 clip',
    input: z.object({
      roomId,
      nodeId: nodeIdSchema,
      clip: z.string().optional(),
      speed: z.number().positive().optional(),
    }),
    output: revisionOut,
    scope: 'room' as const,
    mutating: true,
    wire: 'scene.apply' as const,
    mcp: { tool: 'vibe3d_play_animation' as const },
    cli: { command: 'anim play', args: '<roomId> <nodeId> [--clip <name>] [--speed 1]' },
    errors: ['E_INVALID_PARAMS', 'E_ROOM_NOT_FOUND'] as const,
  },
  'scene.undo': {
    title: '撤销一步',
    input: z.object({ roomId }),
    output: revisionOut,
    scope: 'room' as const,
    mutating: true,
    wire: 'scene.undo' as const,
    mcp: { tool: 'vibe3d_undo' as const, annotations: { readOnlyHint: false } },
    cli: { command: 'scene undo', args: '<roomId>' },
    errors: ['E_INVALID_PARAMS', 'E_ROOM_NOT_FOUND'] as const,
  },
  'scene.redo': {
    title: '重做一步',
    input: z.object({ roomId }),
    output: revisionOut,
    scope: 'room' as const,
    mutating: true,
    wire: 'scene.redo' as const,
    mcp: { tool: 'vibe3d_redo' as const, annotations: { readOnlyHint: false } },
    cli: { command: 'scene redo', args: '<roomId>' },
    errors: ['E_INVALID_PARAMS', 'E_ROOM_NOT_FOUND'] as const,
  },
  'scene.diff': {
    title: '两点版本之间的 op 差异',
    input: z.object({
      roomId,
      from: z.number().int().min(0).optional(),
      to: z.number().int().min(0).optional(),
    }),
    output: z.object({
      from: z.number().int(),
      to: z.number().int(),
      ops: opListSchema,
      reset: z.boolean(),
    }),
    scope: 'room' as const,
    mutating: false,
    wire: 'scene.diff' as const,
    mcp: { tool: 'vibe3d_scene_diff' as const, annotations: { readOnlyHint: true } },
    cli: { command: 'scene diff', args: '<roomId> [--from n] [--to n]' },
    errors: ['E_INVALID_PARAMS', 'E_ROOM_NOT_FOUND'] as const,
  },
  'selection.get': {
    title: '读取 UI 当前选中',
    input: z.object({ roomId }),
    output: z.object({ nodeIds: z.array(nodeIdSchema) }),
    scope: 'room' as const,
    mutating: false,
    wire: 'selection.get' as const,
    mcp: { tool: 'vibe3d_get_selection' as const, annotations: { readOnlyHint: true } },
    cli: { command: 'selection get', args: '<roomId>' },
  },
};
