import { PROTOCOL_VERSION } from '@vibebyte/vibe3d-protocol';
import type { z } from 'zod';
import { zodToJsonSchema } from 'zod-to-json-schema';
import { CAPABILITIES, CAPABILITY_NAMES } from '../registry';
import type { CapabilitySpec } from '../types';

const HEADER = '// AUTO-GENERATED by pnpm gen - do not edit by hand.';

const toJsonSchema = (schema: z.ZodType<unknown>): Record<string, unknown> =>
  zodToJsonSchema(schema, { target: 'jsonSchema7', $refStrategy: 'none' }) as Record<string, unknown>;

const snake = (key: string): string => key.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`);

export function snakeKeys(schema: unknown): unknown {
  if (Array.isArray(schema)) return schema.map(snakeKeys);
  if (!schema || typeof schema !== 'object') return schema;
  const out: Record<string, unknown> = {};
  for (const [key, value] of Object.entries(schema as Record<string, unknown>)) {
    if (key === 'properties' && value && typeof value === 'object') {
      const props: Record<string, unknown> = {};
      for (const [prop, sub] of Object.entries(value as Record<string, unknown>)) {
        props[snake(prop)] = snakeKeys(sub);
      }
      out[key] = props;
      continue;
    }
    if (key === 'required' && Array.isArray(value)) {
      out[key] = value.map((v) => (typeof v === 'string' ? snake(v) : v));
      continue;
    }
    out[key] = snakeKeys(value);
  }
  return out;
}

const specOf = (name: string): CapabilitySpec<unknown, unknown> =>
  CAPABILITIES[name as keyof typeof CAPABILITIES] as CapabilitySpec<unknown, unknown>;

/**
 * 房间是连接层状态：room 级能力的 room_id 不进工具 schema，
 * 只有声明 mcp.roomArg 的能力（房间本身是操作对象）保留一个可选 room_id。
 */
function mcpInputSchema(spec: CapabilitySpec<unknown, unknown>): Record<string, unknown> {
  const schema = snakeKeys(toJsonSchema(spec.input)) as {
    properties?: Record<string, unknown>;
    required?: string[];
  };
  if (spec.scope !== 'room') return schema as Record<string, unknown>;
  const keep = (key: string): boolean => key !== 'room_id';
  const properties = Object.fromEntries(Object.entries(schema.properties ?? {}).filter(([key]) => keep(key)));
  const required = (schema.required ?? []).filter(keep);
  if (spec.mcp?.roomArg) {
    properties.room_id = {
      type: 'string',
      pattern: '^r_[a-z0-9]{8}$',
      description: '房间 id；省略时用当前会话绑定的房间',
    };
  }
  const out: Record<string, unknown> = { ...schema, properties };
  out.required = required.length > 0 ? required : undefined;
  return out;
}

export function buildSpecDoc(): Record<string, unknown> {
  return {
    protocolVersion: PROTOCOL_VERSION,
    package: '@vibebyte/vibe3d-capabilities',
    capabilities: CAPABILITY_NAMES.map((name) => {
      const spec = specOf(name);
      return {
        name,
        title: spec.title,
        wire: spec.wire,
        scope: spec.scope,
        mutating: spec.mutating,
        hostCoupled: spec.hostCoupled ?? false,
        errors: [...(spec.errors ?? [])],
        mcp: spec.mcp
          ? {
              tool: spec.mcp.tool,
              annotations: spec.mcp.annotations ?? {},
              roomArg: spec.mcp.roomArg ?? false,
            }
          : null,
        cli: spec.cli ?? null,
        input: toJsonSchema(spec.input),
        output: toJsonSchema(spec.output),
      };
    }),
  };
}

export function buildTypes(): string {
  const names = CAPABILITY_NAMES.map((n) => `  | ${JSON.stringify(n)}`).join('\n');
  const inputs = CAPABILITY_NAMES.map(
    (n) => `  ${JSON.stringify(n)}: z.infer<(typeof CAPABILITIES)[${JSON.stringify(n)}]['input']>;`,
  ).join('\n');
  const outputs = CAPABILITY_NAMES.map(
    (n) => `  ${JSON.stringify(n)}: z.infer<(typeof CAPABILITIES)[${JSON.stringify(n)}]['output']>;`,
  ).join('\n');
  return [
    HEADER,
    "import type { z } from 'zod';",
    "import { CAPABILITIES } from '../src/registry';",
    '',
    'export type CapabilityName =',
    `${names};`,
    '',
    'export type InputOf<N extends CapabilityName> = {',
    inputs,
    '}[N];',
    '',
    'export type OutputOf<N extends CapabilityName> = {',
    outputs,
    '}[N];',
    '',
  ].join('\n');
}

export function buildCli(): string {
  const rows = CAPABILITY_NAMES.map((name) => {
    const cli = specOf(name).cli;
    if (!cli) return null;
    return `  { command: ${JSON.stringify(cli.command)}, args: ${JSON.stringify(cli.args)}, capability: ${JSON.stringify(name)} },`;
  }).filter(Boolean);
  return [HEADER, 'export const CLI_COMMANDS = [', ...rows.map((r) => r as string), '] as const;', ''].join(
    '\n',
  );
}

export function buildMcp(): string {
  const rows = CAPABILITY_NAMES.map((name) => {
    const spec = specOf(name);
    if (!spec.mcp) return null;
    const schema = mcpInputSchema(spec);
    return [
      '  {',
      `    name: ${JSON.stringify(spec.mcp.tool)},`,
      `    title: ${JSON.stringify(spec.title)},`,
      `    capability: ${JSON.stringify(name)},`,
      `    annotations: ${JSON.stringify(spec.mcp.annotations ?? {})},`,
      `    inputSchema: ${JSON.stringify(schema, null, 2).replace(/\n/g, '\n    ')},`,
      '  },',
    ].join('\n');
  }).filter(Boolean);
  return [HEADER, 'export const MCP_TOOLS = [', ...rows.map((r) => r as string), '] as const;', ''].join(
    '\n',
  );
}

export function generateFiles(): Record<string, string> {
  return {
    'spec.json': `${JSON.stringify(buildSpecDoc(), null, 2)}\n`,
    'types.ts': buildTypes(),
    'cli.ts': buildCli(),
    'mcp.ts': buildMcp(),
  };
}
