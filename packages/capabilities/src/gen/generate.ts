import { PROTOCOL_VERSION } from '@vibebyte/vibe3d-protocol';
import type { z } from 'zod';
import { zodToJsonSchema } from 'zod-to-json-schema';
import { CAPABILITIES, CAPABILITY_NAMES } from '../registry';
import {
  GROUP_BY_CAPABILITY,
  LEGACY_OF,
  LEGACY_TOOL_ALIASES,
  TOOL_GROUPS,
  groupAnnotations,
  isFlatTool,
} from '../tool-groups';
import type { ToolGroup } from '../tool-groups';
import type { CapabilitySpec } from '../types';

const HEADER = '// AUTO-GENERATED by pnpm gen - do not edit by hand.';

export const JSON_SCHEMA_DIALECT = 'https://json-schema.org/draft/2020-12/schema';

/**
 * Make a JSON Schema safe for MCP 2020-12 and strict LLM gateways alike:
 * draft-07 tuple `items: [a, b]` became invalid in 2020-12 (prefixItems took
 * over) and GLM-family endpoints reject the whole tools array on sight. Collapse
 * homogeneous tuples into a single item schema plus minItems/maxItems, degrade
 * mixed ones to anyOf, and pin every embedded $schema to the 2020-12 dialect.
 */
export function mcpSafe(schema: unknown): unknown {
  if (Array.isArray(schema)) return schema.map(mcpSafe);
  if (!schema || typeof schema !== 'object') return schema;
  const src = schema as Record<string, unknown>;
  const out: Record<string, unknown> = {};
  for (const [key, value] of Object.entries(src)) {
    if (key === 'items' && Array.isArray(value) && value.length > 0) {
      const elems = value.map(mcpSafe);
      const homogeneous = elems.every((e) => JSON.stringify(e) === JSON.stringify(elems[0]));
      out.items = homogeneous ? elems[0] : { anyOf: elems };
      continue;
    }
    if (key === '$schema') {
      out[key] = JSON_SCHEMA_DIALECT;
      continue;
    }
    out[key] = mcpSafe(value);
  }
  if (Array.isArray(src.items) && src.items.length > 0) {
    if (out.minItems === undefined) out.minItems = src.items.length;
    if (out.maxItems === undefined) out.maxItems = src.items.length;
  }
  return out;
}

const toJsonSchema = (schema: z.ZodType<unknown>): Record<string, unknown> =>
  zodToJsonSchema(schema, { target: 'jsonSchema7', $refStrategy: 'none' }) as Record<string, unknown>;

const snake = (key: string): string => key.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`);

export function snakeKeys(schema: unknown): unknown {
  if (Array.isArray(schema)) return schema.map(snakeKeys);
  if (!schema || typeof schema !== 'object') return schema;
  const out: Record<string, unknown> = {};
  for (const [key, value] of Object.entries(schema as Record<string, unknown>)) {
    if (key === 'properties' && value && typeof value === 'object') {
      const props: Record<string, unknown> = {};
      for (const [prop, sub] of Object.entries(value as Record<string, unknown>)) {
        props[snake(prop)] = snakeKeys(sub);
      }
      out[key] = props;
      continue;
    }
    if (key === 'required' && Array.isArray(value)) {
      out[key] = value.map((v) => (typeof v === 'string' ? snake(v) : v));
      continue;
    }
    out[key] = snakeKeys(value);
  }
  return out;
}

const specOf = (name: string): CapabilitySpec<unknown, unknown> =>
  CAPABILITIES[name as keyof typeof CAPABILITIES] as CapabilitySpec<unknown, unknown>;

/**
 * 房间是连接层状态：room 级能力的 room_id 不进工具 schema，
 * 只有声明 mcp.roomArg 的能力（房间本身是操作对象）保留一个可选 room_id。
 */
export function mcpInputSchema(spec: CapabilitySpec<unknown, unknown>): Record<string, unknown> {
  const schema = mcpSafe(snakeKeys(toJsonSchema(spec.input))) as {
    properties?: Record<string, unknown>;
    required?: string[];
  };
  if (spec.scope !== 'room') return { $schema: JSON_SCHEMA_DIALECT, ...schema };
  const keep = (key: string): boolean => key !== 'room_id';
  const properties = Object.fromEntries(Object.entries(schema.properties ?? {}).filter(([key]) => keep(key)));
  const required = (schema.required ?? []).filter(keep);
  if (spec.mcp?.roomArg) {
    properties.room_id =
      spec.mcp.roomArg === 'required'
        ? {
            type: 'string',
            pattern: '^r_[a-z0-9]{8}$',
            description: '要切换到的房间 id（必填）：只换绑定，不打开窗口。先用 vibe3d_list_rooms 取 id。',
          }
        : {
            type: 'string',
            pattern: '^r_[a-z0-9]{8}$',
            description: '房间 id；省略时用当前会话绑定的房间',
          };
    if (spec.mcp.roomArg === 'required') required.push('room_id');
  }
  const out: Record<string, unknown> = { $schema: JSON_SCHEMA_DIALECT, ...schema, properties };
  out.required = required.length > 0 ? required : undefined;
  return out;
}

export function buildSpecDoc(): Record<string, unknown> {
  return {
    protocolVersion: PROTOCOL_VERSION,
    package: '@vibebyte/vibe3d-capabilities',
    capabilities: CAPABILITY_NAMES.map((name) => {
      const spec = specOf(name);
      return {
        name,
        title: spec.title,
        wire: spec.wire,
        scope: spec.scope,
        mutating: spec.mutating,
        hostCoupled: spec.hostCoupled ?? false,
        errors: [...(spec.errors ?? [])],
        mcp: GROUP_BY_CAPABILITY.has(name)
          ? {
              tool: GROUP_BY_CAPABILITY.get(name)?.group.tool ?? null,
              op: GROUP_BY_CAPABILITY.get(name)?.op ?? null,
              legacy: LEGACY_OF.get(name) ?? null,
              annotations: spec.mcp?.annotations ?? {},
              roomArg: spec.mcp?.roomArg ?? false,
            }
          : null,
        cli: spec.cli ?? null,
        input: toJsonSchema(spec.input),
        output: toJsonSchema(spec.output),
      };
    }),
  };
}

export function buildTypes(): string {
  const names = CAPABILITY_NAMES.map((n) => `  | ${JSON.stringify(n)}`).join('\n');
  const inputs = CAPABILITY_NAMES.map(
    (n) => `  ${JSON.stringify(n)}: z.infer<(typeof CAPABILITIES)[${JSON.stringify(n)}]['input']>;`,
  ).join('\n');
  const outputs = CAPABILITY_NAMES.map(
    (n) => `  ${JSON.stringify(n)}: z.infer<(typeof CAPABILITIES)[${JSON.stringify(n)}]['output']>;`,
  ).join('\n');
  return [
    HEADER,
    "import type { z } from 'zod';",
    "import { CAPABILITIES } from '../src/registry';",
    '',
    'export type CapabilityName =',
    `${names};`,
    '',
    'export type InputOf<N extends CapabilityName> = {',
    inputs,
    '}[N];',
    '',
    'export type OutputOf<N extends CapabilityName> = {',
    outputs,
    '}[N];',
    '',
  ].join('\n');
}

export function buildCli(): string {
  const rows = CAPABILITY_NAMES.map((name) => {
    const cli = specOf(name).cli;
    if (!cli) return null;
    return `  { command: ${JSON.stringify(cli.command)}, args: ${JSON.stringify(cli.args)}, capability: ${JSON.stringify(name)} },`;
  }).filter(Boolean);
  return [HEADER, 'export const CLI_COMMANDS = [', ...rows.map((r) => r as string), '] as const;', ''].join(
    '\n',
  );
}

/** 多 op 工具的统一信封：{ op, params }，参数细节交给 vibe3d_help，避免把 N 份 schema 塞进工具表 */
function envelopeSchema(group: ToolGroup): Record<string, unknown> {
  const properties: Record<string, unknown> = {
    op: {
      type: 'string',
      enum: group.ops.map(([op]) => op),
      description: `${group.tool.slice('vibe3d_'.length)} 下的 op；每个 op 的参数字段用 vibe3d_help {tool, op} 查`,
    },
    params: {
      type: 'object',
      description: 'op 的具名参数（snake_case）。省略 params 时取其顶层字段：{ op: "create", kind: "mesh", name: "cube" }',
    },
  };
  if (group.ops.some(([, capability]) => specOf(capability).mcp?.roomArg)) {
    properties.room_id = { type: 'string', pattern: '^r_[a-z0-9]{8}$', description: '房间 id；省略时用当前会话绑定的房间' };
  }
  return {
    $schema: JSON_SCHEMA_DIALECT,
    type: 'object',
    properties,
    required: ['op'],
    additionalProperties: true,
  };
}

export function buildMcp(): string {
  const rows = TOOL_GROUPS.map((group) => {
    const [first] = group.ops;
    if (!first) throw new Error(`${group.tool}: 没有 op`);
    const flat = isFlatTool(group);
    const schema = flat ? mcpInputSchema(specOf(first[1])) : envelopeSchema(group);
    const ops = group.ops
      .map(
        ([op, capability]) =>
          `{ op: ${JSON.stringify(op)}, capability: ${JSON.stringify(capability)}, title: ${JSON.stringify(specOf(capability).title)} }`,
      )
      .join(',\n      ');
    return [
      '  {',
      `    name: ${JSON.stringify(group.tool)},`,
      `    title: ${JSON.stringify(group.title)},`,
      `    ops: [\n      ${ops},\n    ],`,
      `    annotations: ${JSON.stringify(groupAnnotations(group))},`,
      `    inputSchema: ${JSON.stringify(schema, null, 2).replace(/\n/g, '\n    ')},`,
      '  },',
    ].join('\n');
  });
  const aliases = [...LEGACY_TOOL_ALIASES.entries()]
    .map(([legacy, target]) => `  ${JSON.stringify(legacy)}: { tool: ${JSON.stringify(target.tool)}, op: ${JSON.stringify(target.op)} },`)
    .join('\n');
  return [
    HEADER,
    "import type { McpToolDoc } from '../src/types';",
    '',
    'export const MCP_TOOLS: readonly McpToolDoc[] = [',
    ...rows,
    '];',
    '',
    '/** 旧版扁平工具名 → { tool, op }，仅作过渡别名 */',
    'export const MCP_LEGACY_ALIASES: Readonly<Record<string, { tool: string; op: string }>> = {',
    aliases,
    '};',
    '',
  ].join('\n');
}

export function generateFiles(): Record<string, string> {
  return {
    'spec.json': `${JSON.stringify(buildSpecDoc(), null, 2)}\n`,
    'types.ts': buildTypes(),
    'cli.ts': buildCli(),
    'mcp.ts': buildMcp(),
  };
}
